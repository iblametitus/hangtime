"""All Pydantic schemas (docs/SPEC.md section 4).

LLM calls derive their JSON schema from these models, so keep field names stable.
"""

from enum import Enum

from pydantic import BaseModel, Field, model_validator


class Pattern(str, Enum):
    squat = "squat"
    hinge = "hinge"
    lunge = "lunge"
    jump_vertical = "jump_vertical"
    jump_horizontal = "jump_horizontal"
    bound = "bound"
    hop_unilateral = "hop_unilateral"
    landing = "landing"
    calf_ankle = "calf_ankle"
    sprint = "sprint"
    core = "core"
    other = "other"


class FVZone(str, Enum):  # force-velocity curve; order defines "adjacent"
    max_strength = "max_strength"
    strength_speed = "strength_speed"
    speed_strength = "speed_strength"
    reactive = "reactive"  # fast stretch-shortening cycle


class SSC(str, Enum):  # order defines "adjacent"
    none = "none"
    slow = "slow"
    fast = "fast"


class Emphasis(str, Enum):
    eccentric = "eccentric"
    isometric = "isometric"
    concentric = "concentric"
    mixed = "mixed"


class Resistance(str, Enum):
    bodyweight = "bodyweight"
    free_weight = "free_weight"
    band = "band"
    chain = "chain"
    machine = "machine"


class HardestPoint(str, Enum):
    bottom = "bottom"
    mid = "mid"
    top = "top"
    even = "even"


class Laterality(str, Enum):
    bilateral = "bilateral"
    unilateral = "unilateral"


class Goal(str, Enum):
    vertical_jump = "vertical_jump"
    sprint_speed = "sprint_speed"
    injury_resilience = "injury_resilience"
    general_athleticism = "general_athleticism"


class Rating(str, Enum):
    well_supported = "well_supported"
    partly_supported = "partly_supported"
    unsupported = "unsupported"
    myth = "myth"


class EvidencePath(str, Enum):
    direct = "direct"  # measures jump, sprint or strength outcomes
    indirect = "indirect"  # injury risk, tendon health, pain, availability


class Fit(str, Enum):
    good_fit = "good_fit"
    conditional = "conditional"
    not_recommended = "not_recommended"


# Controlled vocabularies. Free strings in the schema, but the swap filter compares
# them against the user's profile, so seed data and the onboarding form use these.
EQUIPMENT = [
    "none", "box", "barbell", "trap_bar", "dumbbell", "kettlebell", "band",
    "bench", "hurdle", "medicine_ball", "sled", "cable", "machine", "rack", "step",
]
CONTRAINDICATIONS = [
    "knee_pain", "ankle_instability", "low_back_pain", "achilles_tendinopathy",
    "patellar_tendinopathy", "hamstring_strain", "shoulder_pain", "hip_pain",
]


class LoadCost(BaseModel):
    fatigue: int = Field(ge=1, le=3)
    joint_stress: int = Field(ge=1, le=3)
    ground_contacts_per_rep: int = Field(ge=0)  # 0 for strength exercises


class ExerciseProfile(BaseModel):
    id: str  # slug, e.g. "depth-jump"
    name: str
    aliases: list[str]
    pattern: Pattern
    laterality: Laterality
    fv_zone: FVZone
    ssc: SSC
    emphasis: Emphasis
    resistance: Resistance
    hardest_point: HardestPoint
    load_cost: LoadCost
    equipment: list[str]
    min_training_age_years: float = Field(ge=0)
    rep_min: int = Field(ge=1)  # no tuple: strict JSON schema handles tuples badly
    rep_max: int = Field(ge=1)
    contraindications: list[str]
    evidence_card_ids: list[str]
    reviewed: bool = False
    auto_profiled: bool = False  # True = generated by the LLM for an unknown exercise

    @model_validator(mode="after")
    def _rep_range(self) -> "ExerciseProfile":
        if self.rep_min > self.rep_max:
            raise ValueError("rep_min must be <= rep_max")
        return self


class EvidenceCard(BaseModel):
    id: str  # e.g. "markovic-2007-plyo-meta"
    citation: str
    url: str  # DOI or PubMed link
    study_type: str  # "meta-analysis", "RCT", "review", ...
    population: str
    intervention: str
    duration_weeks: int | None
    outcome_measures: list[str]
    summary: str  # 2-3 sentences, own words
    key_findings: list[str]  # 2-5 short checkable statements (basis of citation check)
    effect_direction: str  # "positive" | "no_effect" | "mixed" | "negative"
    effect_size: str | None  # verbatim from the study, if reported
    exercise_tags: list[str]  # Pattern and FVZone values + exercise IDs
    evidence_path: EvidencePath  # indirect evidence never backs a specific performance promise
    limitations: str
    reviewed: bool = False


class UserProfile(BaseModel):
    goal: Goal
    training_age_years: float
    sessions_per_week: int
    injuries: list[str]
    equipment: list[str]


class PlannedExercise(BaseModel):
    exercise_id: str | None  # None = not recognised in the DB
    raw_name: str
    sets: int
    reps: int
    load: str | None  # "70% 1RM", "bodyweight", "40 cm box"


class Session(BaseModel):
    id: str
    label: str  # "Tuesday – Lower power"
    weekday: int | None  # 0 = Monday
    exercises: list[PlannedExercise]


class TrainingPlan(BaseModel):
    sessions: list[Session]


class CoarseScan(BaseModel):
    exercise_frames: list[int]  # indices 0-7 of frames that show the exercise
    on_screen_text: list[str]  # all on-screen text across the whole video
    multiple_exercises: bool


class VideoUnderstanding(BaseModel):
    movement_description: str
    on_screen_text: list[str]
    equipment_seen: list[str]
    execution_notes: str  # tempo, ground contact, depth, ...


class Claim(BaseModel):
    exercise_name: str
    promised_effect: str  # "+10 cm vertical in 2 weeks" or "" if none
    target_audience: str
    matched_exercise_id: str | None
    match_confidence: float


class SwapProposal(BaseModel):
    session_id: str
    replaces_exercise_id: str
    replaces_raw_name: str
    new_exercise_id: str
    old_prescription: str  # "3×6"
    new_prescription: str  # "3×5"
    similarity: float  # 0-1
    matched_on: list[str]  # ["pattern", "fv_zone", "ssc"]
    volume_note: str  # generated deterministically


class Citation(BaseModel):
    source_id: str
    quote: str


class Verdict(BaseModel):
    rating: Rating
    headline: str  # one sentence
    reasoning: str  # max. 4 sentences
    citations: list[Citation]
    personal_fit: Fit
    personal_fit_reason: str
    swap_explanation: str | None  # explains SwapProposal, invents nothing new
    safety_notes: list[str]
